class HomePage extends StatefulWidget {
  final String language;
  final Function(String) onLanguageChanged;

  const HomePage({
    super.key,
    required this.language,
    required this.onLanguageChanged,
  });

  @override
  State<HomePage> createState() => _HomePageState();
}

class _HomePageState extends State<HomePage> {
  String serverUrl = "";
  final TextEditingController _serverUrlController = TextEditingController();
  final TextEditingController _apiKeyController = TextEditingController();

  bool isConnected = false;
  bool isDemoMode = false;
  bool isLoading = true;
  String? connectionError;

  List<String> crops = [];
  String? selectedCrop;
  Map<String, dynamic>? cropInfo;
  Map<String, dynamic>? weatherData;
  Map<String, dynamic>? forecastData;
  String? forecastWarning;

  bool useCustomData = false;
  int customYear = 2026;
  int customMonth = 10;
  final TextEditingController _price1mController = TextEditingController();
  final TextEditingController _price7dController = TextEditingController();
  final TextEditingController _currentPriceController = TextEditingController();

  int targetYear = 2026;
  int targetMonth = 12;

  final TextEditingController _chatController = TextEditingController();
  List<Map<String, String>> messages = [];
  bool isChatLoading = false;

  int viewMode = 0;

  String t(String key) {
    return translations[widget.language]?[key] ??
        translations["English"]?[key] ??
        key;
  }

  @override
  void initState() {
    super.initState();
    _initApp();
  }

  @override
  void dispose() {
    _serverUrlController.dispose();
    _apiKeyController.dispose();
    _price1mController.dispose();
    _price7dController.dispose();
    _currentPriceController.dispose();
    _chatController.dispose();
    super.dispose();
  }

  String _getDefaultServerUrl() {
    if (kIsWeb) {
      return "http://127.0.0.1:8000/api";
    }
    try {
      if (Platform.isAndroid) {
        return "http://10.0.2.2:8000/api";
      }
    } catch (_) {}
    return "http://127.0.0.1:8000/api";
  }

  Future<void> _initApp() async {
    final prefs = await SharedPreferences.getInstance();
    final savedUrl = prefs.getString('server_url');
    final savedKey = prefs.getString('groq_api_key');
    final savedLang = prefs.getString('language');

    serverUrl = (savedUrl != null && savedUrl.isNotEmpty)
        ? savedUrl
        : _getDefaultServerUrl();
    _serverUrlController.text = serverUrl;
    _apiKeyController.text = savedKey ?? '';

    if (savedLang != null && (savedLang == "English" || savedLang == "मराठी")) {
      widget.onLanguageChanged(savedLang);
    }

    await _checkConnectionAndLoad();
  }

  Future<void> _saveSettings() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('server_url', _serverUrlController.text.trim());
    await prefs.setString('groq_api_key', _apiKeyController.text.trim());
    await prefs.setString('language', widget.language);

    setState(() {
      serverUrl = _serverUrlController.text.trim();
    });

    await _checkConnectionAndLoad();
  }

  Future<void> _checkConnectionAndLoad() async {
    setState(() {
      isLoading = true;
      connectionError = null;
    });

    try {
      final res = await http
          .get(Uri.parse('$serverUrl/health'))
          .timeout(const Duration(seconds: 4));
      if (res.statusCode == 200) {
        setState(() {
          isConnected = true;
          isDemoMode = false;
        });
        await _fetchCrops();
        await _fetchWeather();
        if (selectedCrop != null) {
          await _fetchCropInfoAndForecast();
        }
      } else {
        throw Exception("Server status ${res.statusCode}");
      }
    } catch (e) {
      setState(() {
        isConnected = false;
        connectionError = e.toString();
      });
      _enableDemoMode();
    } finally {
      setState(() {
        isLoading = false;
      });
    }
  }

  Future<void> _fetchCrops() async {
    try {
      final res = await http.get(Uri.parse('$serverUrl/crops'));
      if (res.statusCode == 200) {
        final list = List<String>.from(jsonDecode(res.body));
        setState(() {
          crops = list;
          if (crops.isNotEmpty && (selectedCrop == null || !crops.contains(selectedCrop))) {
            selectedCrop = crops[0];
          }
        });
      }
    } catch (_) {}
  }

  Future<void> _fetchWeather() async {
    try {
      final res = await http.get(Uri.parse('$serverUrl/weather'));
      if (res.statusCode == 200) {
        setState(() {
          weatherData = jsonDecode(res.body);
        });
      }
    } catch (_) {}
  }

  Future<void> _fetchCropInfoAndForecast() async {
    if (selectedCrop == null) return;
    setState(() {
      isLoading = true;
    });

    try {
      final infoRes =
          await http.get(Uri.parse('$serverUrl/crop-info/$selectedCrop'));
      if (infoRes.statusCode == 200) {
        final info = jsonDecode(infoRes.body);
        setState(() {
          cropInfo = info;
          if (!useCustomData) {
            _price1mController.text =
                info['default_price_1_month_ago'].toString();
            _price7dController.text =
                info['default_price_7_days_ago'].toString();
            _currentPriceController.text =
                info['default_market_price_2026'].toString();
            customYear = info['current_year'] ?? 2026;
            customMonth = info['current_month'] ?? 10;
          }
        });
      }

      await _executeForecast();
    } catch (e) {
      setState(() {
        connectionError = e.toString();
      });
    } finally {
      setState(() {
        isLoading = false;
      });
    }
  }

  Future<void> _executeForecast() async {
    if (selectedCrop == null) return;
    setState(() {
      isLoading = true;
    });

    if (isDemoMode) {
      _generateDemoForecast();
      setState(() {
        isLoading = false;
      });
      return;
    }

    try {
      final body = {
        "crop": selectedCrop,
        "target_year": targetYear,
        "target_month": targetMonth,
        "use_custom_data": useCustomData,
        "custom_year": customYear,
        "custom_month": customMonth,
        "price_1_month_ago": double.tryParse(_price1mController.text),
        "price_7_days_ago": double.tryParse(_price7dController.text),
        "custom_price": double.tryParse(_currentPriceController.text),
      };

      final res = await http.post(
        Uri.parse('$serverUrl/forecast'),
        headers: {"Content-Type": "application/json"},
        body: jsonEncode(body),
      );

      if (res.statusCode == 200) {
        final data = jsonDecode(utf8.decode(res.bodyBytes));
        setState(() {
          forecastData = data;
          forecastWarning = data['warning'];
        });
      } else {
        setState(() {
          forecastWarning = "Error ${res.statusCode}: ${res.body}";
        });
      }
    } catch (e) {
      setState(() {
        forecastWarning = "Network error: $e";
      });
    } finally {
      setState(() {
        isLoading = false;
      });
    }
  }

