  }

  Future<void> _sendMessage([String? quickText]) async {
    final text = quickText ?? _chatController.text.trim();
    if (text.isEmpty) return;

    setState(() {
      messages.add({"role": "user", "content": text});
      if (quickText == null) _chatController.clear();
      isChatLoading = true;
    });

    if (isDemoMode) {
      await Future.delayed(const Duration(milliseconds: 800));
      setState(() {
        final answer = widget.language == "मराठी"
            ? "🌾 $selectedCrop सल्ला: पुढील काही महिन्यांत बाजारातील आवक संतुलित राहील. अंदाजानुसार भावात ३% ते ७% वाढ अपेक्षित आहे. हवामान अनुकूल असून काढणी व साठवणुकीची काळजी घ्या. टीप: हे केवळ अंदाजित भाव आहेत."
            : "🌾 $selectedCrop Advisory: Prices are projected to rise steadily by 3% to 7% over the forecast horizon. Temperature averages around 29.6°C indicate favorable drying and post-harvest storage. Note: These are predicted prices and not guaranteed.";
        messages.add({"role": "assistant", "content": answer});
        isChatLoading = false;
      });
      return;
    }

    String forecastText = "";
    if (forecastData != null && forecastData!['forecast'] != null) {
      final preds = forecastData!['forecast'] as List;
      for (var p in preds) {
        forecastText +=
            "${p['month']}: ₹${p['price']} (Rain: ${p['rain']}mm)\n";
      }
    }

    String weatherText = "";
    if (weatherData != null) {
      weatherText =
          "Temp: ${weatherData!['avg_temp']}°C, Rain: ${weatherData!['total_rain']}mm, Humidity: ${weatherData!['avg_humidity']}%, Wind: ${weatherData!['avg_wind']}km/h";
    }

    try {
      final res = await http.post(
        Uri.parse('$serverUrl/chat'),
        headers: {"Content-Type": "application/json"},
        body: jsonEncode({
          "crop": selectedCrop,
          "messages": messages,
          "forecast_text": forecastText,
          "weather_text": weatherText,
          "language": widget.language,
          "api_key": _apiKeyController.text.trim().isNotEmpty
              ? _apiKeyController.text.trim()
              : null,
        }),
      );

      if (res.statusCode == 200) {
        final data = jsonDecode(utf8.decode(res.bodyBytes));
        setState(() {
          messages.add({"role": "assistant", "content": data['response']});
        });
      } else {
        setState(() {
          messages.add({
            "role": "assistant",
            "content": "⚠️ Error (${res.statusCode}): ${res.body}"
          });
        });
      }
    } catch (e) {
      setState(() {
        messages.add({
          "role": "assistant",
          "content": "⚠️ Connection error to AI server: $e"
        });
      });
    } finally {
      setState(() {
        isChatLoading = false;
      });
    }
  }

