  Widget _buildChartWidget() {
    final hist = (forecastData!['historical'] as List? ?? []);
    final fore = (forecastData!['forecast'] as List? ?? []);

    List<FlSpot> histSpots = [];
    List<FlSpot> foreSpots = [];
    List<String> monthLabels = [];

    double minPrice = double.infinity;
    double maxPrice = 0;

    int idx = 0;
    for (var h in hist) {
      final p = (h['price'] as num).toDouble();
      histSpots.add(FlSpot(idx.toDouble(), p));
      monthLabels.add(h['month'].toString());
      if (p < minPrice) minPrice = p;
      if (p > maxPrice) maxPrice = p;
      idx++;
    }

    if (histSpots.isNotEmpty) {
      foreSpots.add(histSpots.last);
    }

    for (var f in fore) {
      final p = (f['price'] as num).toDouble();
      foreSpots.add(FlSpot(idx.toDouble(), p));
      monthLabels.add(f['month'].toString());
      if (p < minPrice) minPrice = p;
      if (p > maxPrice) maxPrice = p;
      idx++;
    }

    if (maxPrice == 0) maxPrice = 10000;
    if (minPrice == double.infinity) minPrice = 0;

    return Column(
      children: [
        Wrap(
          alignment: WrapAlignment.center,
          crossAxisAlignment: WrapCrossAlignment.center,
          spacing: 16,
          runSpacing: 6,
          children: [
            Row(
              mainAxisSize: MainAxisSize.min,
              children: [
                Container(width: 14, height: 4, color: Colors.blue),
                const SizedBox(width: 6),
                Text(
                  "${t('type_historical')} / ${t('type_current')}",
                  style: const TextStyle(fontSize: 11, fontWeight: FontWeight.bold),
                ),
              ],
            ),
            Row(
              mainAxisSize: MainAxisSize.min,
              children: [
                Container(width: 14, height: 4, color: Colors.orange),
                const SizedBox(width: 6),
                Text(
                  t('type_predicted'),
                  style: const TextStyle(fontSize: 11, fontWeight: FontWeight.bold),
                ),
              ],
            ),
          ],
        ),
        const SizedBox(height: 12),
        AspectRatio(
          aspectRatio: 1.4,
          child: Padding(
            padding: const EdgeInsets.only(right: 12.0, top: 8),
            child: LineChart(
              LineChartData(
                gridData: FlGridData(
                  show: true,
                  drawVerticalLine: false,
                  getDrawingHorizontalLine: (val) => FlLine(
                    color: Colors.grey.shade200,
                    strokeWidth: 1,
                  ),
                ),
                titlesData: FlTitlesData(
                  bottomTitles: AxisTitles(
                    sideTitles: SideTitles(
                      showTitles: true,
                      reservedSize: 26,
                      interval: (monthLabels.length / 4).ceilToDouble(),
                      getTitlesWidget: (val, meta) {
                        int i = val.toInt();
                        if (i >= 0 && i < monthLabels.length) {
                          final m = monthLabels[i];
                          final parts = m.split('-');
                          if (parts.length == 2) {
                            return Text(
                              "${parts[1]}/${parts[0].substring(2)}",
                              style: const TextStyle(fontSize: 10),
                            );
                          }
                          return Text(m, style: const TextStyle(fontSize: 10));
                        }
                        return const SizedBox.shrink();
                      },
                    ),
                  ),
                  leftTitles: AxisTitles(
                    sideTitles: SideTitles(
                      showTitles: true,
                      reservedSize: 45,
                      getTitlesWidget: (val, meta) {
                        return Text(
                          "₹${(val / 1000).toStringAsFixed(1)}k",
                          style: const TextStyle(fontSize: 9),
                        );
                      },
                    ),
                  ),
                  topTitles: const AxisTitles(
                    sideTitles: SideTitles(showTitles: false),
                  ),
                  rightTitles: const AxisTitles(
                    sideTitles: SideTitles(showTitles: false),
                  ),
                ),
                borderData: FlBorderData(
                  show: true,
                  border: Border.all(color: Colors.grey.shade300),
                ),
                minX: 0,
                maxX: (idx > 0 ? (idx - 1) : 1).toDouble(),
                minY: minPrice * 0.9,
                maxY: maxPrice * 1.1,
                lineTouchData: LineTouchData(
                  touchTooltipData: LineTouchTooltipData(
                    getTooltipItems: (touchedSpots) {
                      return touchedSpots.map((spot) {
                        int index = spot.x.toInt();
                        String date = index < monthLabels.length
                            ? monthLabels[index]
                            : "";
                        return LineTooltipItem(
                          "$date\n₹${spot.y.toStringAsFixed(2)}",
                          const TextStyle(
                            color: Colors.white,
                            fontSize: 11,
                            fontWeight: FontWeight.bold,
                          ),
                        );
                      }).toList();
                    },
                  ),
                ),
                lineBarsData: [
                  LineChartBarData(
                    spots: histSpots,
                    isCurved: true,
                    color: Colors.blue.shade700,
                    barWidth: 3,
                    dotData: const FlDotData(show: true),
                  ),
                  LineChartBarData(
                    spots: foreSpots,
                    isCurved: true,
                    color: Colors.orange.shade700,
                    barWidth: 3,
                    dotData: const FlDotData(show: true),
                    dashArray: [5, 4],
                  ),
                ],
              ),
            ),
          ),
        ),
      ],
    );
  }

  Widget _buildTableWidget() {
    final hist = (forecastData!['historical'] as List? ?? []);
    final fore = (forecastData!['forecast'] as List? ?? []);
    final allRows = [...hist, ...fore];

    return Container(
      constraints: const BoxConstraints(maxHeight: 280),
      child: ListView.separated(
        shrinkWrap: true,
        itemCount: allRows.length,
        separatorBuilder: (_, __) => const Divider(height: 1),
        itemBuilder: (ctx, i) {
          final row = allRows[i];
          final monthStr = "${row['month']}";
          String type = row['type'] ?? "";

          // Safeguard: Any date prior to 2026 cannot be "Current"
          final year = int.tryParse(monthStr.split("-").first) ?? 2025;
          if (year < 2026 && type == "Current") {
            type = "Historical";
          }

          Color badgeColor = Colors.grey;
          String typeText = t('type_historical');

          if (type == "Current") {
            badgeColor = Colors.blue;
            typeText = t('type_current');
          } else if (type == "Predicted") {
            badgeColor = Colors.orange;
            typeText = t('type_predicted');
          }

          return Padding(
            padding: const EdgeInsets.symmetric(horizontal: 8.0, vertical: 8.0),
            child: Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Text(
                  "${row['month']}",
                  style: const TextStyle(
                    fontWeight: FontWeight.bold,
                    fontSize: 13,
                  ),
                ),
                Text(
                  "₹ ${(row['price'] as num).toStringAsFixed(2)}",
                  style: const TextStyle(
                    fontWeight: FontWeight.w600,
                    fontSize: 14,
                  ),
                ),
                Container(
                  padding:
                      const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                  decoration: BoxDecoration(
                    color: badgeColor == Colors.blue
                        ? Colors.blue.shade50
                        : (badgeColor == Colors.orange
                            ? Colors.orange.shade50
                            : Colors.grey.shade100),
                    borderRadius: BorderRadius.circular(6),
                    border: Border.all(color: badgeColor),
                  ),
                  child: Text(
                    typeText,
                    style: TextStyle(
                      color: badgeColor,
                      fontSize: 10,
                      fontWeight: FontWeight.bold,
                    ),
                  ),
                )
              ],
            ),
          );
        },
      ),
    );
  }

